// Pre-builds the frontend for production. Vercel can't serve Bun's HTML imports, so the bundle is
// written into src/generated/web-assets.ts and ships inside the server function itself.
import { join } from "path";

const root = join(import.meta.dir, "..");
const out = join(root, "src/generated/web-assets.ts");

const result = await Bun.build({
  entrypoints: [join(root, "web/index.html")],
  minify: true,
  publicPath: "/",
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!result.success) throw new AggregateError(result.logs, "Frontend build failed");

type Asset = { body: string; type: string; immutable: boolean };
const assets: Record<string, Asset> = {};

for (const output of result.outputs) {
  if (!/^text\/|javascript|json|svg/.test(output.type)) throw new Error(`Unexpected binary build output: ${output.path}`);
  const path = output.path.replace(/^\./, "");
  // Hashed chunks can be cached forever; the page itself must always be fresh.
  assets[path] = { body: await output.text(), type: output.type, immutable: path !== "/index.html" };
}

// The stylesheet is linked at runtime (see web/index.html), so the bundler doesn't see it.
assets["/styles.css"] = {
  body: await Bun.file(join(root, "web/styles.css")).text(),
  type: "text/css;charset=utf-8",
  immutable: false,
};

if (!assets["/index.html"]) throw new Error("Build produced no index.html");

await Bun.write(
  out,
  `// Generated by scripts/build-web.ts for production. Do not edit.
import type { WebAssets } from "./web-assets-type";

export const WEB_ASSETS: WebAssets | null = ${JSON.stringify(assets)};
`,
);
console.log(`built ${Object.keys(assets).length} assets → ${out}`);
for (const [path, a] of Object.entries(assets)) console.log(`  ${path}  ${(a.body.length / 1024).toFixed(0)} KB`);
